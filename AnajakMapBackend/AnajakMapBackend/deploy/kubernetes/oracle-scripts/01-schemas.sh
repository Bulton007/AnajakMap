#!/bin/bash
set -euo pipefail
sqlplus -s / as sysdba <<SQL
WHENEVER SQLERROR EXIT SQL.SQLCODE
ALTER SESSION SET CONTAINER=FREEPDB1;
DECLARE n NUMBER; BEGIN
 SELECT COUNT(*) INTO n FROM dba_users WHERE username='IDENTITY';
 IF n=0 THEN EXECUTE IMMEDIATE 'CREATE USER IDENTITY IDENTIFIED BY "${IDENTITY_DB_PASSWORD}"'; END IF;
END;
/
GRANT CREATE SESSION, CREATE TABLE, CREATE SEQUENCE, CREATE TRIGGER, CREATE PROCEDURE TO IDENTITY;
ALTER USER IDENTITY QUOTA UNLIMITED ON USERS;
SQL
