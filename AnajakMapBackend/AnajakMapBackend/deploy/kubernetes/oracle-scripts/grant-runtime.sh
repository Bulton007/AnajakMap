#!/bin/bash
set -euo pipefail
sqlplus -s / as sysdba <<SQL
WHENEVER SQLERROR EXIT SQL.SQLCODE
ALTER SESSION SET CONTAINER=FREEPDB1;
DECLARE n NUMBER; BEGIN
 SELECT COUNT(*) INTO n FROM dba_users WHERE username='IDENTITY_APP';
 IF n=0 THEN EXECUTE IMMEDIATE 'CREATE USER IDENTITY_APP IDENTIFIED BY "${IDENTITY_APP_PASSWORD}"'; END IF;
END;
/
GRANT CREATE SESSION TO IDENTITY_APP;
BEGIN
 FOR t IN(SELECT table_name FROM dba_tables WHERE owner='IDENTITY' AND table_name<>'flyway_schema_history') LOOP
  IF t.table_name='BUSINESS_AUDIT' THEN
   EXECUTE IMMEDIATE 'GRANT SELECT, INSERT ON IDENTITY.'||t.table_name||' TO IDENTITY_APP';
  ELSE
   EXECUTE IMMEDIATE 'GRANT SELECT, INSERT, UPDATE, DELETE ON IDENTITY.'||t.table_name||' TO IDENTITY_APP';
  END IF;
 END LOOP;
END;
/
